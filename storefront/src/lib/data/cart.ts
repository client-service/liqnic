/**
 * Retrieves a cart by its ID. If no ID is provided, it will use the cart ID from the cookies.
 * @param cartId - optional - The ID of the cart to retrieve.
 * @returns The cart object if found, or null if not found.
 */
export async function retrieveCart(cartId?: string) {
  const id = cartId || (await getCartId())

  if (!id) {
    return null
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  const next = {
    ...(await getCacheOptions("carts")),
    revalidate: 60,
  }

  return await sdk.client
    .fetch<HttpTypes.StoreCartResponse>(`/store/carts/${id}`, {
      method: "GET",
      query: {
        fields:
          "id, currency_code, total, subtotal, tax_total, discount_total, shipping_total, item_total, email, metadata, region.id, region.name, region.currency_code, region.countries.iso_2, region.countries.display_name, shipping_methods.name, shipping_methods.amount, shipping_address.first_name, shipping_address.last_name, shipping_address.address_1, shipping_address.address_2, shipping_address.city, shipping_address.country_code, shipping_address.province, shipping_address.postal_code, shipping_address.phone, shipping_address.company, billing_address.first_name, billing_address.last_name, billing_address.address_1, billing_address.address_2, billing_address.city, billing_address.country_code, billing_address.province, billing_address.postal_code, billing_address.phone, billing_address.company, items.id, items.title, items.product_title, items.product_handle, items.thumbnail, items.quantity, items.total, items.original_total, items.unit_price, items.subtotal, items.tax_total, items.tax_lines.rate, items.tax_lines.description, items.tax_lines.code, items.variant.id, items.variant.title, items.variant.sku, items.variant.manage_inventory, items.variant.inventory_quantity, items.product.title, items.product.handle, items.product.thumbnail",
      },
      headers,
      next,
      cache: "force-cache",
    })
    .then(({ cart }) => cart)
    .catch(() => null)
}

export async function getOrSetCart(countryCode: string) {
  const region = await getRegion(countryCode)

  if (!region) {
    throw new Error(`Region not found for country code: ${countryCode}`)
  }

  let cart = await retrieveCart()

  const headers = {
    ...(await getAuthHeaders()),
  }

  if (!cart) {
    const cartResp = await sdk.store.cart.create(
      { region_id: region.id },
      {},
      headers
    )
    cart = cartResp.cart

    await setCartId(cart.id)

    const cartCacheTag = await getCacheTag("carts")
    revalidateTag(cartCacheTag)
  }

  if (cart && cart?.region_id !== region.id) {
    await sdk.store.cart.update(cart.id, { region_id: region.id }, {}, headers)
    const cartCacheTag = await getCacheTag("carts")
    revalidateTag(cartCacheTag)
  }

  return cart
}

export async function updateCart(data: HttpTypes.StoreUpdateCart) {
  const cartId = await getCartId()

  if (!cartId) {
    throw new Error("No existing cart found, please create one before updating")
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  return sdk.store.cart
    .update(cartId, data, {}, headers)
    .then(async ({ cart }) => {
      const cartCacheTag = await getCacheTag("carts")
      revalidateTag(cartCacheTag)

      const fulfillmentCacheTag = await getCacheTag("fulfillment")
      revalidateTag(fulfillmentCacheTag)

      return cart
    })
    .catch(medusaError)
}

